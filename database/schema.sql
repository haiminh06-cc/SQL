-- Bootstrap chỉ cho DB demo mới. Không chạy trên DB nhóm hiện có.
-- Không rerun khi bảng đã tồn tại; không DROP/ghi đè dữ liệu.
CREATE DATABASE IF NOT EXISTS QuanLySanBong_demo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE QuanLySanBong_demo;

CREATE TABLE KHACHHANG (
    MaKH INT AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    DiaChi VARCHAR(200)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE NHANVIEN (
    MaNV INT AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(15) NOT NULL,
    ChucVu VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE LOAISAN (
    MaLoai INT AUTO_INCREMENT PRIMARY KEY,
    TenLoai VARCHAR(50) NOT NULL,
    SoNguoi INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DICHVU (
    MaDV INT AUTO_INCREMENT PRIMARY KEY,
    TenDV VARCHAR(100) NOT NULL,
    DonViTinh VARCHAR(30) NOT NULL,
    DonGia DECIMAL(12,2) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DOIBONG (
    MaDoi INT AUTO_INCREMENT PRIMARY KEY,
    TenDoi VARCHAR(100) NOT NULL,
    TenDoiTruong VARCHAR(100),
    SoDienThoai VARCHAR(15)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE GIAIDAU (
    MaGiai INT AUTO_INCREMENT PRIMARY KEY,
    TenGiai VARCHAR(100) NOT NULL,
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE SANBONG (
    MaSan INT AUTO_INCREMENT PRIMARY KEY,
    TenSan VARCHAR(50) NOT NULL,
    MaLoai INT NOT NULL,
    GiaThue DECIMAL(12,2) NOT NULL,
    TinhTrang VARCHAR(30) NOT NULL,

    FOREIGN KEY (MaLoai) REFERENCES LOAISAN(MaLoai)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE DAT_SAN (
    MaDatSan INT AUTO_INCREMENT PRIMARY KEY,
    MaKH INT NOT NULL,
    MaSan INT NOT NULL,
    MaNV INT NOT NULL,
    ThoiGianBatDau DATETIME NOT NULL,
    ThoiGianKetThuc DATETIME NOT NULL,
    GiaThueLucDat DECIMAL(12,2) NOT NULL,
    TrangThai VARCHAR(30) NOT NULL,

    INDEX idx_dat_san_lich (MaSan, ThoiGianBatDau, ThoiGianKetThuc),
    FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH),
    FOREIGN KEY (MaSan) REFERENCES SANBONG(MaSan),
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CHITIET_DICHVU (
    MaDatSan INT NOT NULL,
    MaDV INT NOT NULL,
    SoLuong INT NOT NULL,
    DonGiaLucDung DECIMAL(12,2) NOT NULL,

    PRIMARY KEY (MaDatSan, MaDV),

    FOREIGN KEY (MaDatSan) REFERENCES DAT_SAN(MaDatSan),
    FOREIGN KEY (MaDV) REFERENCES DICHVU(MaDV)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE HOADON (
    MaHD INT AUTO_INCREMENT PRIMARY KEY,
    MaDatSan INT NOT NULL,
    MaNV INT NOT NULL,
    NgayLap DATE NOT NULL,
    TongTien DECIMAL(12,2) NOT NULL,
    TrangThaiThanhToan VARCHAR(30) NOT NULL,

    UNIQUE KEY uq_hoadon_dat_san (MaDatSan),
    FOREIGN KEY (MaDatSan) REFERENCES DAT_SAN(MaDatSan),
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE THAMGIA_GIAIDAU (
    MaGiai INT NOT NULL,
    MaDoi INT NOT NULL,

    PRIMARY KEY (MaGiai, MaDoi),

    FOREIGN KEY (MaGiai) REFERENCES GIAIDAU(MaGiai),
    FOREIGN KEY (MaDoi) REFERENCES DOIBONG(MaDoi)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE TRANDAU (
    MaTran INT AUTO_INCREMENT PRIMARY KEY,
    MaGiai INT NOT NULL,
    MaSan INT NOT NULL,
    MaDoiNha INT NOT NULL,
    MaDoiKhach INT NOT NULL,
    ThoiGianThiDau DATETIME NOT NULL,
    TySoNha INT,
    TySoKhach INT,

    FOREIGN KEY (MaGiai) REFERENCES GIAIDAU(MaGiai),
    FOREIGN KEY (MaSan) REFERENCES SANBONG(MaSan),
    FOREIGN KEY (MaDoiNha) REFERENCES DOIBONG(MaDoi),
    FOREIGN KEY (MaDoiKhach) REFERENCES DOIBONG(MaDoi)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
